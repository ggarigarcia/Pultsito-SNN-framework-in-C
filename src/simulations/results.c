void store_number_of_spikes_array(GPU_results_t **results, simulation_configuration_t *conf, size_t N, size_t batch_size, size_t n_results){

    size_t i;

    for(i = 0; i<n_results; i++){

        store_number_of_spikes(results[i], conf, N, batch_size);
    }
}

void store_number_of_spikes(GPU_results_t *results, simulation_configuration_t *conf, size_t N, size_t batch_size){

    size_t i, b;
    FILE *f;

    // open file for storing the results
    open_file_w(&f, conf->n_spikes_per_neuron_file);

    for(b = 0; b<conf->batch_size; b++){

        for(i = 0; i<N; i++){
            fprintf(f, "%d ", results->n_spks[i * batch_size + b]);
        }
        fprintf(f, "\n");
    }

    fclose(f);
}

void store_generated_spikes_array(GPU_results_t **results, simulation_configuration_t *conf, size_t N, size_t batch_size, size_t T, size_t n_results){

    size_t i;

    for(i = 0; i<n_results; i++){

        store_generated_spikes(results[i], conf, N, batch_size, T);
    }
}

void store_generated_spikes(GPU_results_t *results, simulation_configuration_t *conf, size_t N, size_t batch_size, size_t T){

    size_t i, b, t;
    FILE *f;

    // open file for storing the results
    open_file_w(&f, conf->generated_spikes_file);

    for(b = 0; b<batch_size; b++){
            
        for(i = 0; i<N; i++){

            for(t = 0; t<T; t++){
            
                if(results->gnt_spks[t * batch_size * N + i * batch_size + b] == 1){
                    fprintf(f, "|");
                }
                else{
                    fprintf(f, " ");
                }
            }
            fprintf(f, "\n");        
        }
        fprintf(f, "\n");
    }

    fclose(f);
}

void deallocate_results_str(GPU_results_t *results){

    if(results->n_spks)
        free(results->n_spks);
    if(results->gnt_spks)
        free(results->gnt_spks);

    // * liberar matriz circular
    if(results->matrix_t){
        free(results->matrix_t->matrix);
        free(results->matrix_t->cumulative);
        free(results->matrix_t->neuron_to_cluster);
        free(results->matrix_t);
    }

    if(results)
        free(results);
}

void acc_batch_execution_times(GPU_results_t *results, GPU_results_t *batch_results){

    results->t        += batch_results->t;        // total execution time
    results->t_in     += batch_results->t_in;     // time processing input spikes
    results->t_v      += batch_results->t_v;      // time processing neurons dynamics
    results->t_out    += batch_results->t_out;    // time processing output spikes
    results->t_learn  += batch_results->t_learn;  // time learning
    results->t_reinit += batch_results->t_reinit; // network reinitialization
    results->t_load   += batch_results->t_load;   // loading sample or batch in network
}


void display_cluster_spike_matrices(GPU_results_t **results, size_t n_batches, size_t time_steps){

    size_t n_cl = 0, B = 0;
    if(n_batches > 0 && results[0]->matrix_t){
        n_cl = results[0]->matrix_t->n_clusters;
        B = results[0]->matrix_t->batch_size;
    }
    if(n_cl == 0) return;

    // accumulator across batches (global scope)
    int *global_cum = (int*)calloc(n_cl, sizeof(int));

    for(size_t b = 0; b < n_batches; b++){

        cluster_spk_buffer_t *mtx = results[b]->matrix_t;
        if(!mtx) continue;

        size_t n_ts = mtx->n_timesteps;
        size_t cs = mtx->current_step;

        printf("\n=== Batch %zu === (buffer: %zut x %zu clusters x %zu batch)\n", b, n_ts, n_cl, B);

        // matrix: timestep rows, cluster columns, summed over batch
        printf("%-6s", "");
        for(size_t c = 0; c < n_cl; c++) printf(" %7s%zu", "c", c);
        printf("\n");

        for(size_t r = 0; r < n_ts; r++){

            size_t idx = (cs + 1 + r) % n_ts; // oldest → newest

            int gt = (int)time_steps - (int)n_ts + (int)r;
            if(gt < 0) printf("%-6s", "---");
            else       printf("t=%-3d", gt);

            for(size_t c = 0; c < n_cl; c++){

                int sum = 0;
                for(size_t e = 0; e < B; e++)
                    sum += mtx->matrix[idx * n_cl * B + c * B + e];
                printf(" %8d", sum);
            }
            printf("\n");
        }

        // per-batch cumulative
        int batch_sum = 0;
        printf("\nBatch cumulative:");
        for(size_t c = 0; c < n_cl; c++){
            int sum = 0;
            for(size_t e = 0; e < B; e++)
                sum += mtx->cumulative[c * B + e];
            global_cum[c] += sum;
            batch_sum += sum;
            printf(" c%zu=%d", c, sum);
        }

        // global cumulative (accumulated across all batches so far)
        printf("\nGlobal cumulative: ");
        int global_sum = 0;
        for(size_t c = 0; c < n_cl; c++){
            printf("c%zu=%d ", c, global_cum[c]);
            global_sum += global_cum[c];
        }
        printf("(total=%d, batch=%d)\n", global_sum, batch_sum);
    }

    free(global_cum);
}

